#!/usr/bin/env python3
"""Splits each bundled font into a core file and an extended one, so a browser fetches
only what a book uses (the engine and the page load the same files).

    python3 scripts/subset-fonts.py        (needs fontTools: pip install fonttools)

Reads assets-src/fonts/*.ttf (the fonts as published) and assets/fonts/core-ranges.txt.
Writes assets/fonts/<name>.ttf (the core: Latin, punctuation, symbols) and
assets/fonts/<name>.ext.ttf (everything else the font has), and
app/src/styles/fonts.css: an @font-face for each, the core's and the extension's
unicode-range exact, so the browser picks a file per character as the engine's chain
does ("Literata", then "Literata~ext"). Checks that the two files together map every
character the original did, to glyphs of the same width.
"""
import os, sys
from fontTools.ttLib import TTFont
from fontTools import subset

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
SRC = os.path.join(ROOT, 'assets-src/fonts')
OUT = os.path.join(ROOT, 'assets/fonts')
CSS = os.path.join(ROOT, 'app/src/styles/fonts.css')

# family, file, weight (CSS), style — the same as app/src/core/fonts.ts
FACES = [
    ('Literata', 'Literata', '100 1000', 'normal'), ('Literata', 'Literata-Italic', '100 1000', 'italic'),
    ('Inter', 'Inter', '100 1000', 'normal'), ('Inter', 'Inter-Italic', '100 1000', 'italic'),
    ('Newsreader', 'Newsreader', '100 1000', 'normal'), ('Newsreader', 'Newsreader-Italic', '100 1000', 'italic'),
    ('Fraunces', 'Fraunces', '100 1000', 'normal'), ('Fraunces', 'Fraunces-Italic', '100 1000', 'italic'),
    ('Nunito Sans', 'NunitoSans', '100 1000', 'normal'), ('Nunito Sans', 'NunitoSans-Italic', '100 1000', 'italic'),
    ('JetBrains Mono', 'JetBrainsMono', '100 1000', 'normal'),
] + [('Charis', f'Charis-{n}', str(w), s) for w, (u, i) in zip((400, 500, 600, 700), (('Regular', 'Italic'), ('Medium', 'MediumItalic'), ('SemiBold', 'SemiBoldItalic'), ('Bold', 'BoldItalic'))) for n, s in ((u, 'normal'), (i, 'italic'))]


def core_ranges():
    out = []
    for line in open(os.path.join(OUT, 'core-ranges.txt')):
        line = line.split('#')[0].strip()
        if not line:
            continue
        a, _, b = line.partition('-')
        out.append((int(a, 16), int(b or a, 16)))
    return out


def in_ranges(c, ranges):
    return any(a <= c <= b for a, b in ranges)


def compact(cps):
    """Code points as unicode-range text: runs joined."""
    cps = sorted(cps)
    out, i = [], 0
    while i < len(cps):
        j = i
        while j + 1 < len(cps) and cps[j + 1] == cps[j] + 1:
            j += 1
        out.append(f'U+{cps[i]:X}' if i == j else f'U+{cps[i]:X}-{cps[j]:X}')
        i = j + 1
    return ', '.join(out)


def cut(src, dst, cps):
    opts = subset.Options()
    opts.layout_features = ['*']       # every feature a theme may ask for
    opts.hinting = True                # keep `prep`: FreeType autohints a font without it
    opts.notdef_outline = True
    opts.name_IDs = ['*']
    opts.name_languages = ['*']
    opts.glyph_names = False
    opts.legacy_kern = True
    opts.symbol_cmap = True
    f = TTFont(src)
    s = subset.Subsetter(opts)
    s.populate(unicodes=cps)
    s.subset(f)
    f.save(dst)


def widths(path):
    f = TTFont(path)
    cmap, hmtx = f.getBestCmap(), f['hmtx'].metrics
    return {c: hmtx[g][0] for c, g in cmap.items()}


def main():
    core = core_ranges()
    css = ['/* Generated by scripts/subset-fonts.py: do not edit. Each bundled face is two files,',
           '   the core and the rest, by unicode-range, as the engine chains "Name", "Name~ext". */']
    total = [0, 0, 0]
    for fam, name, weight, style in FACES:
        src = os.path.join(SRC, name + '.ttf')
        cmap = TTFont(src).getBestCmap()
        all_cps = set(cmap)
        core_cps = {c for c in all_cps if in_ranges(c, core)}
        ext_cps = all_cps - core_cps
        cut(src, os.path.join(OUT, name + '.ttf'), core_cps)
        cut(src, os.path.join(OUT, name + '.ext.ttf'), ext_cps)
        # the split loses nothing and changes no width
        w0, wc, we = widths(src), widths(os.path.join(OUT, name + '.ttf')), widths(os.path.join(OUT, name + '.ext.ttf'))
        assert set(wc) == core_cps and set(we) == ext_cps, name
        bad = [c for c in all_cps if (wc.get(c) if c in core_cps else we.get(c)) != w0[c]]
        assert not bad, f'{name}: widths differ for {bad[:5]}'
        sizes = [os.path.getsize(p) for p in (src, os.path.join(OUT, name + '.ttf'), os.path.join(OUT, name + '.ext.ttf'))]
        total = [t + s for t, s in zip(total, sizes)]
        print(f'{name:24s} {sizes[0] // 1024:5d} KB → core {sizes[1] // 1024:4d} KB + ext {sizes[2] // 1024:4d} KB  ({len(core_cps)} + {len(ext_cps)} characters)')
        core_range = ', '.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in core)
        common = f'font-weight: {weight}; font-style: {style}; font-display: block;'
        css.append(f'@font-face {{ font-family: "{fam}"; src: url("/fonts/{name}.ttf") format("truetype"); {common} unicode-range: {core_range}; }}')
        if ext_cps:
            css.append(f'@font-face {{ font-family: "{fam}"; src: url("/fonts/{name}.ext.ttf") format("truetype"); {common} unicode-range: {compact(ext_cps)}; }}')
    open(CSS, 'w').write('\n'.join(css) + '\n')
    print(f'all: {total[0] // 1024} KB → {total[1] // 1024} KB core + {total[2] // 1024} KB ext; wrote {os.path.relpath(CSS, ROOT)}')


if __name__ == '__main__':
    sys.exit(main())
